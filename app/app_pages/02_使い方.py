"""使い方ページ(叩き台):アプリの操作手順・用語・よくある質問。"""

import streamlit as st

st.title("使い方がわからない時は")
st.write("このアプリでは、サッカー選手の市場価値(推定移籍金額)とその推移を確認できます。")

# --- 操作手順 ---
st.header("基本の使い方")
st.markdown(
    """
1. サイドバーの **メインページ** を開きます
2. **選手を検索** の欄に選手名を入力すると、候補が絞り込まれます(英語表記で入力してください。例:`Haaland`)
3. 選手を選ぶと、基本情報・現在の市場価値・リーグ内順位が表示されます
4. **市場価値の推移** のグラフで、これまでの査定額の変化を確認できます。点にカーソルを合わせると、査定日と金額が表示されます
5. 細かい数値を見たい場合は、**査定履歴(表)** を開いてください
"""
)

# --- 用語 ---
st.header("用語の説明")
st.table(
    {
        "用語": ["市場価値", "自己最高額", "前週比", "リーグ内順位", "査定日"],
        "意味": [
            "Transfermarkt が推定した選手の移籍金相当額(ユーロ)。実際の移籍金とは異なります",
            "その選手がこれまでに付いた市場価値の最高額",
            "先週の記録と比べた市場価値の増減",
            "同じリーグに所属する選手の中での、市場価値の順位",
            "Transfermarkt で市場価値が更新された日。毎日更新されるわけではありません",
        ],
    }
)
st.caption("金額は €M(百万ユーロ)、€k(千ユーロ)で表記しています。")

# --- よくある質問 ---
st.header("よくある質問")
with st.expander("選手が見つかりません"):
    st.write(
        "現在はプレミアリーグに所属する選手のみを収録しています。"
        "また、選手名は英語表記で検索してください。"
    )
with st.expander("前週比が表示されません"):
    st.write("前週比は、週1回の記録が2週分たまると表示されます。")
with st.expander("グラフが階段のような形になっているのはなぜですか?"):
    st.write(
        "市場価値は査定日にだけ更新され、次の査定日までは同じ金額のままです。"
        "その実態に合わせて、階段状のグラフで表示しています。"
    )
with st.expander("データはいつ更新されますか?"):
    st.write("週1回、自動で更新しています。詳しくは「データソースについて」をご覧ください。")
